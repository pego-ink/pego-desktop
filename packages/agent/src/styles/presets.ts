const normalize = (value: string): string =>
  value
    .toLowerCase()
    .replace(/[\s_]+/g, "-")
    .trim();

export const findStyle = (name: string): StylePreset | undefined =>
  stylePresets.find((preset) => preset.name === normalize(name));
